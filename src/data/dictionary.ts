export function lookupWord(word: string): string | null {
  const clean = word.toLowerCase().replace(/[^a-z]/g, '');
  if (!clean) return null;
  // Direct lookup
  if (EN_PT[clean]) return EN_PT[clean];
  // Try removing common suffixes
  const stems = [
    clean.replace(/ing$/, ''),
    clean.replace(/ed$/, ''),
    clean.replace(/s$/, ''),
    clean.replace(/es$/, ''),
    clean.replace(/er$/, ''),
    clean.replace(/est$/, ''),
    clean.replace(/ly$/, ''),
    clean.replace(/tion$/, 'te'),
    clean.replace(/ness$/, ''),
    clean.replace(/ment$/, ''),
    clean.replace(/ful$/, ''),
    clean.replace(/less$/, ''),
  ];
  for (const stem of stems) {
    if (EN_PT[stem]) return EN_PT[stem];
  }
  return null;
}
